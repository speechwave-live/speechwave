// Builds assets/vendor/echarts.custom.js from the ECharts npm package.
// Run with `npm run build:echarts` in assets/. The output is committed because
// the production image has no npm step.
import { build } from "esbuild"
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import path from "node:path"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const {version} = JSON.parse(
  readFileSync(path.join(root, "node_modules/echarts/package.json"), "utf8")
)

await build({
  absWorkingDir: root,
  entryPoints: ["scripts/echarts_entry.js"],
  outfile: "vendor/echarts.custom.js",
  bundle: true,
  minify: true,
  format: "esm",
  legalComments: "none",
  banner: {
    js: `// Generated by assets/scripts/build_echarts.mjs from echarts@${version}. Do not edit; run "npm run build:echarts" in assets/.`,
  },
})
